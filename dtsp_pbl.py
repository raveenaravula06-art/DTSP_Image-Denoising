axs[2].set_title("Median Filter")

axs[3].imshow(gaussian_filtered, cmap='gray')
axs[3].set_title("Gaussian Filter")

axs[4].imshow(wiener_filtered, cmap='gray')
axs[4].set_title("Wavelet Denoising")

for ax in axs:
    ax.axis('off')

plt.show()

print("\n--- Final Comparison ---")
compare_images(img, gaussian_noise, "Noisy (Gaussian)")
compare_images(img, sp_noise, "Noisy (Salt & Pepper)")
compare_images(img, mean_filtered, "Mean Filter")
compare_images(img, median_filtered, "Median Filter")
compare_images(img, gaussian_filtered, "Gaussian Filter")
