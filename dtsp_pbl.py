import cv2
import matplotlib.pyplot as plt
import os

extract_path = "/content/dataset" # Assuming this is still defined and correct from earlier

found_image = False
sample_image_path = None

# Use os.walk to find the first image file in any subdirectory
for root, dirs, files in os.walk(extract_path):
    for file in files:
        if file.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.bmp')):
            sample_image_path = os.path.join(root, file)
            found_image = True
            break # Found an image, no need to search further
    if found_image:
        break # Found an image, no need to walk further

if found_image:
    img = cv2.imread(sample_image_path, cv2.IMREAD_GRAYSCALE)

    if img is not None:
        plt.imshow(img, cmap='gray')
        plt.title(f"Original Image from {os.path.basename(os.path.dirname(sample_image_path))}")
        plt.axis('off')
        plt.show()
    else:
        print(f"Error: Could not read the image file at {sample_image_path}. It might be corrupted or not a valid image.")
else:
    print(f"Error: No image files found in the directory tree starting from {extract_path} with common image extensions.")

import numpy as np

# Gaussian Noise
gaussian_noise = img + np.random.normal(0, 50, img.shape)
gaussian_noise = np.clip(gaussian_noise, 0, 255).astype(np.uint8)

# Salt & Pepper Noise
sp_noise = img.copy()
prob = 0.01
rnd = np.random.rand(*img.shape)
sp_noise[rnd < prob/2] = 0
sp_noise[rnd > 1 - prob/2] = 255

# Mean Filter
mean_filtered = cv2.blur(gaussian_noise, (7,7))

# Median Filter
median_filtered = cv2.medianBlur(sp_noise, 5)

# Gaussian Filter
gaussian_filtered = cv2.GaussianBlur(gaussian_noise, (7,7), 0)

# Wavelet Denoising
from skimage.restoration import denoise_wavelet
# Removed 'multichannel=False' as it's no longer a valid argument in newer scikit-image versions for grayscale images
wiener_filtered = denoise_wavelet(gaussian_noise)

plt.figure(figsize=(15, 10))

plt.subplot(2, 4, 1)
plt.imshow(img, cmap='gray')
plt.title("Original Image")
plt.axis('off')

plt.subplot(2, 4, 2)
plt.imshow(gaussian_noise, cmap='gray')
plt.title("Gaussian Noise")
plt.axis('off')

plt.subplot(2, 4, 3)
plt.imshow(sp_noise, cmap='gray')
plt.title("Salt & Pepper Noise")
plt.axis('off')

plt.subplot(2, 4, 4)
plt.imshow(mean_filtered, cmap='gray')
plt.title("Mean Filtered (Gaussian Noise)")
plt.axis('off')

plt.subplot(2, 4, 5)
plt.imshow(median_filtered, cmap='gray')
plt.title("Median Filtered (S&P Noise)")
plt.axis('off')

plt.subplot(2, 4, 6)
plt.imshow(gaussian_filtered, cmap='gray')
plt.title("Gaussian Filtered (Gaussian Noise)")
plt.axis('off')

plt.subplot(2, 4, 7)
# Ensure wavelet filtered output is scaled correctly for display
plt.imshow(wiener_filtered, cmap='gray')
plt.title("Wavelet Denoised (Gaussian Noise)")
plt.axis('off')

plt.tight_layout()
plt.show()

from skimage import metrics

def compare_images(original, restored, title):
    psnr = metrics.peak_signal_noise_ratio(original, restored)
    mse = metrics.mean_squared_error(original, restored)
    print(f"{title} -> PSNR: {psnr:.2f}, MSE: {mse:.2f}")

compare_images(img, mean_filtered, "Mean Filter")
compare_images(img, median_filtered, "Median Filter")
compare_images(img, gaussian_filtered, "Gaussian Filter")
compare_images(img, (wiener_filtered*255).astype(np.uint8), "Wavelet Denoising")

fig, axs = plt.subplots(1,7, figsize=(22,5))

axs[0].imshow(img, cmap='gray')
